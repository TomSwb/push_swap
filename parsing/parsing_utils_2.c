#include "../push_swap.h"
/*
GOAL : initialize stacks with default value (and gain lines)
Return : void
*/
void	stack_initializer(t_stack *st)
{
	st->bench = 0;
	st->flag = 0;
	st->init_size = 0;
	st->size = 0;
	st->disorder = 0;
	st->strategy = NULL;
	st->moves = init_moves();
	st->top = NULL;
}

/*
GOAL : gain lines -> it frees the int list generated by split then return 1
Always return 1
*/
int	freeturn(char **int_lst)
{
	int	i;

	i = -1;
	while (int_lst[++i])
	{
		free (int_lst[i]);
		int_lst[i] = NULL;
	}
	free (int_lst);
	int_lst = NULL;
	return (1);
}

/*
GOAL : calculate the "size" of the stack_a => the number of value in the list
Return : void
*/
void	size_calculator(t_stack *st)
{
	int		id_stop;
	size_t	size;
	t_value	*current;

	size = 0;
	id_stop = -1;
	current = st->top;
	while (current->id != id_stop)
	{
		id_stop = st->top->id;
		size++;
		current = current->next;
	}
	st->init_size = size;
}

t_moves	*init_moves(void)
{
	t_moves	moves;

	moves.pa_moves = 0;
	moves.pb_moves = 0;
	moves.sa_moves = 0;
	moves.sb_moves = 0;
	moves.ss_moves = 0;
	moves.ra_moves = 0;
	moves.rb_moves = 0;
	moves.rr_moves = 0;
	moves.rra_moves = 0;
	moves.rrb_moves = 0;
	moves.rrr_moves = 0;
}