/*
GOAL : gain lines -> it frees the int list generated by split then return 1
Always return 1
*/
int	freeturn(char **int_lst)
{
	int	i;

	i = -1;
	while (int_lst[++i])
	{
		free (int_lst[i]);
		int_lst[i] = NULL;
	}
	free (int_lst);
	int_lst = NULL;
	return (1);
}