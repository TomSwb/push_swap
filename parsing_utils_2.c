/*
GOAL : gain lines -> it frees the int list generated by split then return 1
Always return 1
*/
int	freeturn(char **int_lst)
{
	int	i;

	i = -1;
	while (int_lst[++i])
	{
		free (int_lst[i]);
		int_lst[i] = NULL;
	}
	free (int_lst);
	int_lst = NULL;
	return (1);
}

/*
GOAL : calculate the "size" of the stack_a => the number of value in the list
Return : Size
*/
size_t	size_calculator(t_stack *st)
{
	int		id_stop;
	size_t	size;
	t_value	*current;

	size = 0;
	id_stop = -1;
	current = st->top;
	while (current->id != id_stop)
	{
		id_stop = st->top->id;
		size++;
		current = current->next;
	}
	return (size);
}