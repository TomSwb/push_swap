#include "push_swap.h"
/*
GOAL : initialize stacks with default value (and gain lines)
Return : void
*/
void	stack_initializer(t_stack *st)
{
	st->bench = 0;
	st->flag = 0;
	st->init_size = 0;
	st->size = 0;
	st->disorder = 0;
	st->strat = 0;
	ft_bzero(&st->moves, sizeof(t_moves));
	st->top = NULL;
}

/*
GOAL : gain lines -> it frees the int list generated by split then return 1
Always return 1
*/
int	freeturn(char **int_lst)
{
	int	i;

	i = -1;
	while (int_lst[++i])
	{
		free (int_lst[i]);
		int_lst[i] = NULL;
	}
	free (int_lst);
	int_lst = NULL;
	return (1);
}
